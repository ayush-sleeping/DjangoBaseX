"""
Documentation links and generated folder indexes (BUILD_ORDER 9.6; ENGINEERING_PRACTICES § 15, 25).

Every relative Markdown link in documentation/, the root README.md and AGENTS.md, and .claude/
must resolve against the file that holds it. A scan that finds no files fails: a glob anchored at
the wrong directory would otherwise pass for ever. The ADR template's literal `NNNN` placeholders
are not links. The folder indexes are generated by scripts/doc_index.py; an unindexed doc fails.
"""

import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SCRIPT = REPO / "scripts" / "doc_index.py"

INLINE = re.compile(
    r"(?<!\!)\[[^\]]*\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)|!\[[^\]]*\]\(\s*<?([^)\s>]+)>?"
)
REFERENCE = re.compile(r"^\s{0,3}\[[^\]]+\]:\s*<?(\S+?)>?(?:\s+.*)?$")
INLINE_CODE = re.compile(r"`[^`\n]*`")
SKIPPED_SCHEMES = ("http://", "https://", "mailto:", "tel:", "data:")


def markdown_files(repo: Path) -> list[Path]:
    found = list((repo / "documentation").rglob("*.md"))
    found += [repo / name for name in ("AGENTS.md", "README.md") if (repo / name).is_file()]
    found += list((repo / ".claude").rglob("*.md"))
    return sorted(set(found))


def link_targets(text: str):
    """Yield (line number, target) for every link outside fenced code and inline code."""
    in_fence = False
    for number, line in enumerate(text.splitlines(), start=1):
        if line.lstrip().startswith(("```", "~~~")):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        line = INLINE_CODE.sub("", line)
        for match in INLINE.finditer(line):
            yield number, match.group(1) or match.group(2)
        reference = REFERENCE.match(line)
        if reference:
            yield number, reference.group(1)


def broken_links(repo: Path) -> list[str]:
    problems = []
    for path in markdown_files(repo):
        for number, target in link_targets(path.read_text(encoding="utf-8")):
            if target.startswith("#") or target.lower().startswith(SKIPPED_SCHEMES):
                continue
            if "NNNN" in target:  # the ADR template's placeholder
                continue
            relative = target.split("#", 1)[0].split("?", 1)[0]
            if not relative:
                continue
            if not (path.parent / relative).resolve().exists():
                problems.append(f"{path.relative_to(repo)}:{number} -> {target}")
    return problems


def test_the_scan_finds_the_documentation():
    files = markdown_files(REPO)
    assert files, "scanned zero Markdown files: the repo root is wrong"
    assert REPO / "documentation" / "INDEX.md" in files
    assert REPO / "AGENTS.md" in files


def test_no_relative_markdown_link_is_broken():
    assert broken_links(REPO) == []


def test_the_scanner_catches_a_broken_link(tmp_path):
    (tmp_path / "documentation").mkdir()
    (tmp_path / "documentation" / "real.md").write_text("# Real\n")
    (tmp_path / "documentation" / "page.md").write_text(
        "[ok](real.md#top) [web](https://example.com/x.md) [anchor](#here)\n"
        "[ADR](NNNN-title.md)\n"
        "`[in code](nope.md)`\n"
        "```\n[in fence](nope2.md)\n```\n"
        "[broken](missing.md)\n"
        "[ref]: gone.md\n"
    )
    assert broken_links(tmp_path) == [
        "documentation/page.md:7 -> missing.md",
        "documentation/page.md:8 -> gone.md",
    ]


def test_a_scan_of_an_empty_tree_finds_nothing_to_pass_on(tmp_path):
    assert (
        markdown_files(tmp_path) == []
    )  # test_the_scan_finds_the_documentation would fail on this


def test_every_generated_folder_index_is_current():
    result = subprocess.run(
        [sys.executable, str(SCRIPT), "--check"], capture_output=True, text=True, check=False
    )
    assert result.returncode == 0, result.stderr


def test_an_unindexed_document_fails_the_index_check(tmp_path, monkeypatch):
    sys.path.insert(0, str(SCRIPT.parent))
    try:
        import doc_index
    finally:
        sys.path.remove(str(SCRIPT.parent))
    docs = tmp_path / "documentation"
    for name in doc_index.FOLDERS:
        (docs / name).mkdir(parents=True)
        (docs / name / "a.md").write_text("# A\n")
    monkeypatch.setattr(doc_index, "ROOT", tmp_path)
    monkeypatch.setattr(doc_index, "DOCS", docs)
    assert doc_index.main(["--check"]) == 1  # nothing indexed yet
    assert doc_index.main([]) == 0
    assert doc_index.main(["--check"]) == 0
    (docs / "adr" / "new.md").write_text("# New\n")
    assert doc_index.main(["--check"]) == 1  # a new doc nobody indexed
