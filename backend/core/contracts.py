"""
The contracts the frontend imports instead of re-declaring (FRONTEND_PLATFORM § 24, BUILD_ORDER
8.4a). Each is rendered here and written to frontend/src/generated/ by `manage.py
export_frontend_contracts`; tests/test_contracts_export.py fails when a committed file is stale, so
changing a serializer field, a permission, a status or a nav item without regenerating fails CI.

- openapi.json: drf-spectacular's document; `npm run contracts` turns it into api.d.ts types.
- permissions.ts: registry.permissions, as the typed PermissionCode.
- statuses.ts: registry.statuses, StatusPill's tones.
- ordering.ts: list views' ordering_fields; a column's sortKey must be one of them.
- public-routes.ts: registry.public_routes, what answers signed out.
- localization.ts: the shipped locale defaults, the formatters' last-resort fallback.
- nav-manifest.json: registry.navigation, the route gate and its page test.

The committed files are the BOILERPLATE's own contract: a linked plugin's contributions are left
out, so they are identical with or without a plugin installed (CI runs the suite both ways). A
plugin reaches the frontend at runtime through bootstrap, and types its own codes by augmentation.

Rendering is deterministic: sorted keys, no timestamps, and the schema's deployment-specific title
and description replaced, so two machines produce byte-identical files.
"""

import json
from dataclasses import dataclass
from pathlib import Path

from django.conf import settings
from django.urls import URLPattern, URLResolver, get_resolver

from . import navigation
from .plugins import discover
from .registry import registry

GENERATED_DIR = Path(settings.BASE_DIR).parent / "frontend" / "src" / "generated"
COMMAND = "uv run python manage.py export_frontend_contracts"
TS_HEADER = (
    "// Generated by `manage.py export_frontend_contracts` (FRONTEND_PLATFORM § 24).\n"
    "// Do not edit: change the backend and regenerate.\n"
)
SCHEMA_INFO = {
    "title": "API",
    "description": "Generated contract; deployment identity is not part of it.",
    "version": "contract",
}


@dataclass(frozen=True)
class PluginScope:
    """What the linked plugins contribute, so the export can leave it out."""

    labels: frozenset[str]
    permission_prefixes: frozenset[str]
    route_prefixes: frozenset[str]

    @classmethod
    def installed(cls) -> "PluginScope":
        plugins = discover(Path(settings.BASE_DIR) / "plugins")
        return cls(
            labels=frozenset(p.label for p in plugins),
            permission_prefixes=frozenset(p.prefixes.get("permission", p.label) for p in plugins),
            route_prefixes=frozenset(p.prefixes.get("route", p.label) for p in plugins),
        )

    @classmethod
    def none(cls) -> "PluginScope":
        return cls(frozenset(), frozenset(), frozenset())

    def owns_code(self, code: str) -> bool:
        return code.split(".", 1)[0] in self.permission_prefixes | self.labels

    def owns_route_name(self, url_name: str) -> bool:
        return url_name.split(":", 1)[0] in self.labels | self.route_prefixes

    def owns_path(self, path: str) -> bool:
        api = f"/{settings.API_PREFIX}/"
        return any(path.startswith(f"{api}{prefix}/") for prefix in self.route_prefixes)


def _json(value) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _ts_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


# --- OpenAPI -------------------------------------------------------------------------------------


def _refs(node) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/"):
            found.add(ref)
        for value in node.values():
            found |= _refs(value)
    elif isinstance(node, list):
        for value in node:
            found |= _refs(value)
    return found


def prune_schema(schema: dict, scope: PluginScope) -> dict:
    """Drop plugin paths, then every component nothing left refers to (transitively)."""
    schema = json.loads(json.dumps(schema))  # a private copy
    schema["paths"] = {
        p: ops for p, ops in schema.get("paths", {}).items() if not scope.owns_path(p)
    }
    components = schema.get("components", {})
    keep: set[str] = set()
    frontier = _refs(schema["paths"]) | _refs(schema.get("security", []))
    # Security schemes are referenced by name, not $ref: keep them all.
    while frontier:
        ref = frontier.pop()
        if ref in keep:
            continue
        keep.add(ref)
        _, _, kind, name = ref.split("/", 3)
        frontier |= _refs(components.get(kind, {}).get(name, {}))
    for kind in [k for k in components if k != "securitySchemes"]:
        components[kind] = {
            n: v for n, v in components[kind].items() if f"#/components/{kind}/{n}" in keep
        }
        if not components[kind]:
            del components[kind]
    return schema


def openapi_document(scope: PluginScope) -> dict:
    from drf_spectacular.generators import SchemaGenerator

    schema = SchemaGenerator().get_schema(request=None, public=True)
    schema["info"] = dict(SCHEMA_INFO)
    schema.pop("servers", None)
    return prune_schema(schema, scope)


# --- Registries ----------------------------------------------------------------------------------


def render_permissions(scope: PluginScope) -> str:
    codes = sorted(code for code in registry.permissions.codes() if not scope.owns_code(code))
    entries = "\n".join(f"  {_ts_string(code)}: true;" for code in codes)
    listed = "\n".join(f"  {_ts_string(code)}," for code in codes)
    return (
        TS_HEADER
        + "//\n"
        + "// A plugin adds its own codes by augmentation, from its frontend package:\n"
        + '//   declare module "@/generated/permissions" {\n'
        + '//     interface PermissionCodes { "notes.notes.view": true }\n'
        + "//   }\n"
        + "\n"
        + "export interface PermissionCodes {\n"
        + entries
        + "\n}\n\n"
        + "/** Every permission code: core's, plus any a linked plugin adds by augmentation. */\n"
        + "export type PermissionCode = keyof PermissionCodes;\n\n"
        + "/** Core's codes, as data. */\n"
        + "export const CORE_PERMISSIONS = [\n"
        + listed
        + "\n] as const;\n"
    )


def status_table(scope: PluginScope) -> dict[str, dict]:
    return {
        spec.key: {"label": spec.label, "tone": spec.tone, "transitional": spec.transitional}
        for spec in registry.statuses.specs()
        if spec.key.split(".", 1)[0] not in scope.labels
    }


def render_statuses(scope: PluginScope) -> str:
    rows = "\n".join(
        f"  {_ts_string(key)}: {{ label: {_ts_string(meta['label'])}, "
        f"tone: {_ts_string(meta['tone'])}, "
        f"transitional: {'true' if meta['transitional'] else 'false'} }},"
        for key, meta in sorted(status_table(scope).items())
    )
    return (
        TS_HEADER
        + "//\n"
        + "// The tone of each status, decided once by the app that owns it (registry.statuses).\n"
        + "// At runtime bootstrap's `statuses` (linked plugins included) takes precedence.\n"
        + "\n"
        + 'export type Tone = "ok" | "warn" | "err" | "info" | "neutral";\n'
        + "export type StatusMeta = { label: string; tone: Tone; transitional: boolean };\n\n"
        + "export const STATUSES = {\n"
        + rows
        + "\n} as const satisfies Record<string, StatusMeta>;\n\n"
        + "export type CoreStatusKey = keyof typeof STATUSES;\n"
    )


def _walk(patterns, prefix: str = "", namespace: str = ""):
    for pattern in patterns:
        if isinstance(pattern, URLResolver):
            ns = pattern.namespace or ""
            yield from _walk(
                pattern.url_patterns,
                prefix + str(pattern.pattern),
                f"{namespace}:{ns}".strip(":") if ns else namespace,
            )
        elif isinstance(pattern, URLPattern) and pattern.name:
            yield (f"{namespace}:{pattern.name}" if namespace else pattern.name), pattern


def ordering_table(scope: PluginScope) -> dict[str, list[str]]:
    """route name → the fields its `ordering` accepts, for every list view that declares any."""
    table: dict[str, list[str]] = {}
    for name, pattern in _walk(get_resolver().url_patterns):
        view = getattr(pattern.callback, "cls", None)
        actions = getattr(pattern.callback, "actions", None) or {}
        fields = tuple(getattr(view, "ordering_fields", None) or ())
        if not fields or scope.owns_route_name(name):
            continue
        if actions and "list" not in actions.values():
            continue  # a viewset's detail or custom-action route: only its list route sorts
        table[name] = sorted(fields)
    return dict(sorted(table.items()))


def render_ordering(scope: PluginScope) -> str:
    rows = "\n".join(
        f"  {_ts_string(name)}: [{', '.join(_ts_string(f) for f in fields)}],"
        for name, fields in ordering_table(scope).items()
    )
    return (
        TS_HEADER
        + "//\n"
        + "// The `ordering` values each list endpoint accepts (route name → fields). A\n"
        + "// column's sortKey must be one of its endpoint's (sortable-has-key.test.ts).\n"
        + "\n"
        + "export const ORDERING = {\n"
        + rows
        + ("\n" if rows else "")
        + "} as const satisfies Record<string, readonly string[]>;\n\n"
        + "export type ListEndpoint = keyof typeof ORDERING;\n"
    )


def render_public_routes(scope: PluginScope) -> str:
    routes = {
        n: r for n, r in registry.public_routes.routes().items() if not scope.owns_route_name(n)
    }
    rows = "\n".join(
        f"  {_ts_string(name)}: {_ts_string(reason)}," for name, reason in routes.items()
    )
    return (
        TS_HEADER
        + "//\n"
        + "// The API routes that answer without a session, and why (registry.public_routes).\n"
        + "\n"
        + "export const PUBLIC_ROUTES = {\n"
        + rows
        + "\n} as const;\n"
    )


def render_localization() -> str:
    """The shipped locale defaults (LocalePolicy), so the frontend's last-resort fallback — the API
    unreachable, nothing resolved yet — is the backend's own default, never a literal in frontend
    code (FRONTEND_PLATFORM § 14)."""
    from dataclasses import asdict

    from .formatting import LocalePolicy

    rows = "\n".join(
        f"  {key}: {'null' if value is None else _ts_string(value)},"
        for key, value in sorted(asdict(LocalePolicy()).items())
    )
    return (
        TS_HEADER
        + "//\n"
        + "// The platform's shipped locale defaults (core.formatting.LocalePolicy). Runtime\n"
        + "// values come from bootstrap `localization` (signed in) or /api/public/config/.\n"
        + "\n"
        + "export const SHIPPED_LOCALIZATION = {\n"
        + rows
        + "\n} as const;\n"
    )


# --- The whole set -------------------------------------------------------------------------------


def render_all(scope: PluginScope | None = None) -> dict[str, str]:
    """file name → content, for every generated contract."""
    scope = scope if scope is not None else PluginScope.installed()
    return {
        "openapi.json": _json(openapi_document(scope)),
        "permissions.ts": render_permissions(scope),
        "statuses.ts": render_statuses(scope),
        "ordering.ts": render_ordering(scope),
        "public-routes.ts": render_public_routes(scope),
        "localization.ts": render_localization(),
        "nav-manifest.json": _json(navigation.full_manifest(exclude_modules=scope.labels)),
    }


def stale_files(
    directory: Path = GENERATED_DIR, rendered: dict[str, str] | None = None
) -> list[str]:
    """The generated files whose committed content differs from a fresh render (or is missing)."""
    rendered = rendered if rendered is not None else render_all()
    stale = []
    for name, content in rendered.items():
        path = directory / name
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(name)
    return stale


def write_all(directory: Path = GENERATED_DIR, rendered: dict[str, str] | None = None) -> list[str]:
    rendered = rendered if rendered is not None else render_all()
    directory.mkdir(parents=True, exist_ok=True)
    changed = stale_files(directory, rendered)
    for name in changed:
        (directory / name).write_text(rendered[name], encoding="utf-8")
    return changed
