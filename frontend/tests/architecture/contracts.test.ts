// @vitest-environment node
/**
 * The generated API types are current (FRONTEND_PLATFORM § 24, BUILD_ORDER 8.4 acceptance 1, the
 * frontend half; closes DB-4).
 *
 * The backend's tests/test_contracts_export.py fails when src/generated/openapi.json is stale; this
 * fails when src/generated/api.d.ts was not regenerated from it. Together: change a serializer field
 * without regenerating, and CI fails. Regenerate with `npm run contracts`.
 */
import { readFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

import openapiTS, { astToString, COMMENT_HEADER } from "openapi-typescript";
import { describe, expect, it } from "vitest";

import { SRC } from "./walk";

const GENERATED = path.join(SRC, "generated");

describe("generated contracts", () => {
  it("api.d.ts is exactly what openapi-typescript makes of openapi.json", async () => {
    const schema = pathToFileURL(path.join(GENERATED, "openapi.json"));
    const fresh = `${COMMENT_HEADER}${astToString(await openapiTS(schema))}`;
    const committed = readFileSync(path.join(GENERATED, "api.d.ts"), "utf8");
    expect(committed === fresh, "src/generated/api.d.ts is stale: run `npm run contracts` and commit it").toBe(true);
  }, 30_000);

  it("every generated file says it is generated", () => {
    for (const name of ["permissions.ts", "statuses.ts", "ordering.ts", "public-routes.ts"]) {
      expect(readFileSync(path.join(GENERATED, name), "utf8"), name).toMatch(/^\/\/ Generated by `manage\.py export_frontend_contracts`/);
    }
  });
});
