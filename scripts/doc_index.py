"""
Generated folder indexes for documentation/ (BUILD_ORDER 9.6; ENGINEERING_PRACTICES § 25).

    python3 scripts/doc_index.py            # write README.md in each generated folder
    python3 scripts/doc_index.py --check    # exit 1 if any index is missing or stale

Each folder named in FOLDERS gets a README.md listing every Markdown file in it with its first
heading, so a new doc that nobody indexed is a failing check, not a silent orphan. The root
documentation/INDEX.md is hand-written and is never touched.

Standard library only. Exit codes: 0 current (or written), 1 stale or missing under --check.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "documentation"
FOLDERS = ("adr", "core", "planning", "system-design")
INDEX_NAME = "README.md"
MARKER = (
    "<!-- generated by scripts/doc_index.py - do not edit; run `python3 scripts/doc_index.py` -->"
)


def first_heading(path: Path) -> str:
    in_fence = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("```"):
            in_fence = not in_fence
        elif not in_fence and line.startswith("# "):
            return line[2:].strip()
    return path.stem


def render(folder: Path) -> str:
    rows = [
        f"| [`{p.name}`]({p.name}) | {first_heading(p).replace('|', '/').replace('<', '&lt;')} |"
        for p in sorted(folder.glob("*.md"))
        if p.name != INDEX_NAME
    ]
    return "\n".join(
        [
            f"# {folder.name}/ index",
            "",
            MARKER,
            "",
            "Every document in this folder, with its first heading. "
            "The task map is [`../INDEX.md`](../INDEX.md).",
            "",
            "| File | Title |",
            "|---|---|",
            *rows,
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if an index is missing or stale")
    args = parser.parse_args(argv)

    stale = []
    for name in FOLDERS:
        folder = DOCS / name
        target = folder / INDEX_NAME
        expected = render(folder)
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == expected:
            continue
        if args.check:
            stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(expected, encoding="utf-8")
            print(f"wrote {target.relative_to(ROOT)}")
    if stale:
        print(
            "stale or missing (run `python3 scripts/doc_index.py`): " + ", ".join(stale),
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
